"""G1 safe-stop (π_L1) environment for AAP.

Derived from the stock velocity locomotion task, with:
- near-zero velocity commands (stand / stop)
- stronger orientation / height / alive rewards
- randomized root velocity on reset (handoff-like entry states)
- no walking gait reward or velocity curriculum
"""

